"""
Structured Report Generator — produces Markdown, JSON, and plain-text outputs.
"""
from __future__ import annotations

import json
from datetime import datetime

from src.core.schemas import AnalysisReport, EvidenceRow, EvidenceStrength


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

_STRENGTH_EMOJI = {
    EvidenceStrength.STRONG: "🔴",
    EvidenceStrength.MODERATE: "🟡",
    EvidenceStrength.WEAK: "⚪",
}


def _evidence_table(rows: list[EvidenceRow]) -> str:
    header = (
        "| Clue / Observation | Source | What It Suggests | "
        "Innocent Alternative | Strength |\n"
        "| :--- | :--- | :--- | :--- | :--- |\n"
    )
    lines = []
    for r in rows:
        emoji = _STRENGTH_EMOJI.get(r.strength, "")
        lines.append(
            f"| {r.clue} | {r.source} | {r.suggests} | {r.innocent_alternative} "
            f"| {emoji} {r.strength.value} |"
        )
    return header + "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# Markdown Report
# ─────────────────────────────────────────────────────────────────────────────

def render_markdown(report: AnalysisReport) -> str:
    v = report.verdict
    timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    sections: list[str] = [
        f"# 🔍 Digital Authenticity Report",
        f"**Submission ID:** `{report.submission_id}`  |  **Generated:** {timestamp}  "
        f"|  **File:** {report.filename or 'N/A'}  |  **Type:** {report.media_type.value}",
        "---",
        "## 1. Executive Verdict",
        f"- **Classification:** {v.label.value}",
        f"- **Confidence:** {v.confidence.value}",
        f"- **Bottom Line:** {v.bottom_line}",
        f"- **Biggest Limitation:** {v.biggest_limitation}",
        f"- **Composite Authenticity Score:** `{v.composite_score:.2f}` / 1.00  "
        f"({v.signal_count} check(s) performed)",
        "---",
        "## 2. Evidence Breakdown",
        _evidence_table(report.evidence) if report.evidence else "_No evidence rows collected._",
        "---",
        "## 3. Technical & Source Analysis",
        "**Checks Actually Performed:**",
        "\n".join(f"- ✅ {c}" for c in report.checks_performed) or "_None_",
        "",
        "**Source & Context Verification:**",
        report.source_verification,
        "",
        "**Unperformed / Skipped Tests:**",
        "\n".join(f"- ⏭️ {c}" for c in report.checks_skipped) or "_None_",
        "---",
        "## 4. Risk Assessment & Next Steps",
        f"**Potential Risks:** {report.potential_risks}",
        "",
        f"**How to Get 100% Proof:** {report.how_to_verify}",
        "",
        "---",
        "*Report generated by Digital Authenticity & AI Detection Analyst.*  "
        "*Findings are forensic observations only — not legal determinations.*",
    ]
    return "\n\n".join(sections)


# ─────────────────────────────────────────────────────────────────────────────
# JSON Report
# ─────────────────────────────────────────────────────────────────────────────

def render_json(report: AnalysisReport) -> str:
    return report.model_dump_json(indent=2)


# ─────────────────────────────────────────────────────────────────────────────
# Risk & Verification text builder (called by the pipeline)
# ─────────────────────────────────────────────────────────────────────────────

def build_risk_text(report: AnalysisReport) -> tuple[str, str]:
    """Return (potential_risks, how_to_verify) based on verdict label."""
    from src.core.schemas import VerdictLabel
    label = report.verdict.label

    risks = {
        VerdictLabel.LIKELY_AUTHENTIC: (
            "Low risk based on current evidence. Treat as authentic pending any new contradicting information.",
            "Obtain the original file with full EXIF intact and cross-verify with the issuing organization."
        ),
        VerdictLabel.LIKELY_AI_GENERATED: (
            "High risk of synthetic media being used to deceive — verify identity of the sender and do not act on "
            "the content until confirmed via a trusted out-of-band channel.",
            "Compare against known authentic samples. Request the original uncompressed source file."
        ),
        VerdictLabel.LIKELY_MANIPULATED: (
            "Risk of forged/altered documentation — do not use for financial, legal, or identity purposes without "
            "independent verification.",
            "Request the original signed document from the issuing authority directly (not via the same channel)."
        ),
        VerdictLabel.LIKELY_MISLEADING: (
            "Risk of impersonation, scam, or misinformation campaign. Do not share personal data or transfer funds.",
            "Cross-reference the sender's official website, verified social media, and contact them via a phone "
            "number from a known-good source."
        ),
        VerdictLabel.MIXED: (
            "Moderate risk — some elements appear authentic while others do not. Treat with caution.",
            "Isolate the synthetic / edited element and seek the original from the source."
        ),
        VerdictLabel.INCONCLUSIVE: (
            "Risk level cannot be determined from available evidence. Exercise standard caution.",
            "Configure all API keys, resubmit the original raw file, and run a full scan."
        ),
    }
    return risks.get(label, ("Unknown risk.", "Perform a full forensic scan with the original file."))
